"""Regenerates Shared/Catalog.swift from the Android catalog (which is generated from the Windows ServiceCatalog.cs).

    python tools/gen_catalog.py ../slmtune-android/app/src/main/kotlin/com/slmtune/app/core/Catalog.kt Shared/Catalog.swift
"""
import re
import sys

src = open(sys.argv[1], encoding="utf-8").read()
pat = re.compile(
    r'ServiceDef\("([^"]*)", "([^"]*)", "([^"]*)", "([^"]*)",\s*(listOf\(([^)]*)\)|emptyList\(\)),\s*(listOf\(([^)]*)\)|emptyList\(\))\)',
    re.S,
)
defs = []
for m in pat.finditer(src):
    sid, name, grp, note = m.group(1), m.group(2), m.group(3), m.group(4)
    if grp == "game":  # games need per-app rules, which iOS does not have
        continue
    doms = re.findall(r'"([^"]*)"', m.group(6) or "")
    if not doms:
        continue
    d = ", ".join('"%s"' % x for x in doms)
    defs.append('        ServiceDef(id: "%s", name: "%s", group: .%s, note: "%s",\n                   domains: [%s]),' % (sid, name, grp, note, d))

out = f'''// Generated by tools/gen_catalog.py from the Android/Windows ServiceCatalog (AI and call groups;
// games need per-app rules, which iOS does not have). Regenerate instead of editing the domain lists here.
import Foundation

struct ServiceDef: Identifiable, Hashable {{
    enum Group: String {{ case ai, call }}
    let id: String
    let name: String
    let group: Group
    let note: String
    let domains: [String]
}}

enum Catalog {{
    /// The anti-bot check of ChatGPT, Claude and others must see the same IP as the site.
    static let aiAlways = ["challenges.cloudflare.com"]

    /// Telegram connects to its data centres by IP, not by name.
    static let telegramCidrs = [
        "91.108.4.0/22", "91.108.8.0/22", "91.108.12.0/22", "91.108.16.0/22", "91.108.20.0/22", "91.108.56.0/22",
        "95.161.64.0/20", "149.154.160.0/20", "185.76.151.0/24",
        "2001:b28:f23d::/48", "2001:b28:f23f::/48", "2001:67c:4e8::/48",
    ]

    static let all: [ServiceDef] = [
{chr(10).join(defs)}
    ]

    static func inGroup(_ g: ServiceDef.Group) -> [ServiceDef] {{ all.filter {{ $0.group == g }} }}
}}
'''
open(sys.argv[2], "w", encoding="utf-8", newline="\n").write(out)
print(len(defs), "services")
