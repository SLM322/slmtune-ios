#!/usr/bin/env bash
# Checks everything that doesn't need Xcode, on Linux/WSL:
#  1. compiles Shared/ (links, outbounds, sing-box config, extra-core configs) with Swift and runs Tests/;
#  2. tools/ConfigDump writes the configs the app generates for many scenarios;
#  3. real cores check them: sing-box (`check`), Xray and mihomo (through core/, the same Go code as in the app).
#   wsl -d Ubuntu-24.04 -u root -- bash /mnt/g/slmtune-ios/scripts/linux-check.sh
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
WORK="${WORK_DIR:-$HOME/slmcheck}"
SING_BOX_VERSION="${SING_BOX_VERSION:-1.14.4}"
. "${SWIFTLY_HOME_DIR:-$HOME/.local/share/swiftly}/env.sh" 2>/dev/null || true

mkdir -p "$WORK/Sources" "$WORK/Tests"
ln -sfn "$ROOT/Shared" "$WORK/Sources/SLMShared"
ln -sfn "$ROOT/tools/ConfigDump" "$WORK/Sources/ConfigDump"
ln -sfn "$ROOT/Tests" "$WORK/Tests/SLMSharedTests"
cat > "$WORK/Package.swift" <<'EOF'
// swift-tools-version: 5.9
import PackageDescription

let package = Package(
    name: "SLMShared",
    targets: [
        .target(name: "SLMShared", path: "Sources/SLMShared", swiftSettings: [.unsafeFlags(["-enable-testing"])]),
        .executableTarget(name: "ConfigDump", dependencies: ["SLMShared"], path: "Sources/ConfigDump"),
        .testTarget(name: "SLMSharedTests", dependencies: ["SLMShared"], path: "Tests/SLMSharedTests"),
    ]
)
EOF
cd "$WORK"
echo "== Swift: build and tests"
swift build 2>&1 | grep -E "error|warning: " | grep -v safeExec || true
swift test 2>&1 | grep -E "error|Executed .* tests" | tail -5

echo "== configs generated by the app"
rm -rf "$WORK/configs"
swift run ConfigDump "$WORK/configs" 2>&1 | grep -v safeExec | tail -3

echo "== sing-box $SING_BOX_VERSION check"
SB="$WORK/sing-box-$SING_BOX_VERSION/sing-box"
if [ ! -x "$SB" ]; then
  curl -sSL "https://github.com/SagerNet/sing-box/releases/download/v$SING_BOX_VERSION/sing-box-$SING_BOX_VERSION-linux-amd64.tar.gz" \
    | tar -xz -C "$WORK" && mv "$WORK/sing-box-$SING_BOX_VERSION-linux-amd64" "$WORK/sing-box-$SING_BOX_VERSION"
fi
bad=0
for f in "$WORK"/configs/singbox-*.json; do
  if out=$("$SB" check -c "$f" 2>&1); then echo "ok   $(basename "$f")"; else echo "FAIL $(basename "$f"): $out"; bad=1; fi
done

echo "== Xray and mihomo (core/)"
(cd "$ROOT/core" && GOFLAGS=-buildvcs=false go run -tags slm_bind,badlinkname,tfogo_checklinkname0 -ldflags=-checklinkname=0 ./internal/configcheck "$WORK/configs") 2>&1 | grep -E "config:|^# |link:|cannot" || bad=1
exit $bad
